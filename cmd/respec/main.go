package main

import (
	"encoding/json"
	"fmt"
	"os"
	"strings"

	"github.com/Zachacious/go-respec/internal/analyzer"
	"github.com/Zachacious/go-respec/internal/assembler"
	"github.com/Zachacious/go-respec/internal/config"
	"github.com/Zachacious/go-respec/internal/model"
	"github.com/getkin/kin-openapi/openapi3"
	"github.com/spf13/cobra"
	"gopkg.in/yaml.v3"
)

// These variables are set at build time by the Makefile's ldflags
var (
	version = "dev"
	commit  = "none"
	date    = "unknown"
)

// defaultRespecYAML contains the content for the default .respec.yaml file.
const defaultRespecYAML = `# .respec.yaml - Configuration for the respec OpenAPI generator
#
# Every section is optional. respec works with no config at all; this file is
# for describing the parts of your project it cannot infer.

# High-level information for your OpenAPI specification.
info:
  title: "Untitled API"
  version: "1.0.0"
  description: "A new API generated by respec."

# Servers the API is reachable at.
# servers:
#   - url: "https://api.example.com"
#     description: "Production"

# Security mechanisms your API uses. These names are what you pass to
# .Security("BearerAuth") in code.
securitySchemes:
  BearerAuth:
    type: http
    scheme: bearer
    bearerFormat: JWT
  # ApiKeyAuth:
  #   type: apiKey
  #   in: header          # header, query, or cookie
  #   name: X-API-Key

# Routers respec understands out of the box:
#   chi v5, gin, echo v4, and net/http.ServeMux (Go 1.22+ method patterns).
#
# Add an entry only for a router that is not in that list. Nothing about a
# router is hardcoded in respec - these fields are the whole model.
# routerDefinitions:
#   - type: "github.com/example/router.Router"
#     # Methods named after the HTTP verb: r.Get("/x", h)
#     endpointMethods: ["Get", "Post", "Put", "Patch", "Delete"]
#     # Methods that open a nested scope: r.Route("/users", func(r Router){...})
#     groupMethods: ["Route", "Group"]
#     # Methods that attach middleware: r.Use(mw) / r.With(mw)
#     middlewareWrapperMethods: ["With", "Use"]
#     # Methods that graft an existing sub-router under a prefix.
#     mountMethods: ["Mount"]
#     # "brace" for /users/{id}, "colon" for /users/:id
#     pathParamStyle: "brace"
#     # Registration calls whose arguments are not (path, handler).
#     endpointPatterns:
#       # r.Handle("GET", "/x", h)
#       - methods: ["Handle"]
#         methodArg: 0
#         pathArg: 1
#         handlerArg: 2
#       # mux.HandleFunc("GET /x", h) - verb inside the pattern string
#       - methods: ["HandleFunc"]
#         pathArg: 0
#         handlerArg: 1
#         methodInPath: true
#         # Verbs to document when the pattern names none. Such a pattern
#         # matches all of them, but emitting five near-identical operations
#         # for one static file tree is noise, so the default is a single GET.
#         defaultMethods: ["GET"]

# Teaches respec to recognise your project's own request/response helpers.
# Standard library, gin, and echo patterns are built in.
# handlerPatterns:
#   requestBody:
#     - functionPath: "myapp/internal/httputil.Bind"
#       argIndex: 0
#   responseBody:
#     - functionPath: "myapp/internal/httputil.JSON"
#       statusCodeIndex: 1
#       dataIndex: 2
#   queryParameter:
#     - functionPath: "net/url.Values.Get"
#       nameIndex: 0
#   headerParameter:
#     - functionPath: "net/http.Header.Get"
#       nameIndex: 0

# Maps calls found inside middleware to the security schemes above, so routes
# behind that middleware inherit the requirement.
# securityPatterns:
#   - functionPath: "myapp/internal/auth.ValidateToken"
#     schemeName: "BearerAuth"
`

// reportDiagnostics prints what the analyzer could not resolve, and returns the
// number of warnings.
//
// Everything respec gives up on is reported here. Silently emitting a short
// spec was the worst failure mode the tool had: a wrapped handler simply did
// not appear, with nothing to explain why.
func reportDiagnostics(diags []model.Diagnostic, quiet, verbose bool) int {
	warnings := 0
	for _, d := range diags {
		if d.Severity == "warning" {
			warnings++
		}
	}

	if quiet {
		return warnings
	}

	for _, d := range diags {
		if d.Severity == "info" && !verbose {
			continue
		}
		icon := "⚠"
		if d.Severity == "info" {
			icon = "·"
		}
		if d.Location != "" {
			fmt.Fprintf(os.Stderr, "%s %s: %s\n", icon, d.Location, d.Message)
		} else {
			fmt.Fprintf(os.Stderr, "%s %s\n", icon, d.Message)
		}
	}
	return warnings
}

// countRoutes summarises the assembled spec.
func countRoutes(spec *openapi3.T) (paths int, operations int) {
	if spec.Paths == nil {
		return 0, 0
	}
	for _, item := range spec.Paths.Map() {
		paths++
		operations += len(item.Operations())
	}
	return paths, operations
}

// main is the entry point for the respec command-line tool.
func main() {
	var (
		outputPath string
		quiet      bool
		verbose    bool
		strict     bool
	)

	// rootCmd is the main command for generating the spec.
	var rootCmd = &cobra.Command{
		Use:   "respec [path]",
		Short: "respec is a Go static analysis tool to generate OpenAPI specs without magic comments.",
		Long: `respec analyzes a Go project's source code to infer API routes, handlers,
and schemas, producing a valid OpenAPI v3 specification. It is designed to be
framework-agnostic and highly configurable through a .respec.yaml file.`,
		Args: cobra.MaximumNArgs(1),
		// Progress and diagnostics go to stderr throughout, so the spec itself
		// can be written to stdout and piped.
		Run: func(cmd *cobra.Command, args []string) {
			projectPath := "."
			if len(args) > 0 {
				projectPath = args[0]
			}

			logf := func(format string, a ...any) {
				if !quiet {
					fmt.Fprintf(os.Stderr, format, a...)
				}
			}

			cfg, err := config.Load(projectPath)
			if err != nil {
				fmt.Fprintf(os.Stderr, "Error loading .respec.yaml: %v\n", err)
				os.Exit(1)
			}

			logf("Analyzing %s...\n", projectPath)
			apiModel, err := analyzer.Analyze(projectPath, cfg)
			if err != nil {
				fmt.Fprintf(os.Stderr, "Error during analysis: %v\n", err)
				os.Exit(1)
			}

			spec, err := assembler.BuildSpec(apiModel, cfg)
			if err != nil {
				fmt.Fprintf(os.Stderr, "Error assembling specification: %v\n", err)
				os.Exit(1)
			}

			warnings := reportDiagnostics(apiModel.Diagnostics, quiet, verbose)

			var outputData []byte
			if strings.HasSuffix(strings.ToLower(outputPath), ".json") {
				outputData, err = json.MarshalIndent(spec, "", "  ")
			} else {
				outputData, err = yaml.Marshal(spec)
			}
			if err != nil {
				fmt.Fprintf(os.Stderr, "Error marshalling spec: %v\n", err)
				os.Exit(1)
			}

			if outputPath == "-" {
				if _, err := os.Stdout.Write(outputData); err != nil {
					fmt.Fprintf(os.Stderr, "Error writing spec: %v\n", err)
					os.Exit(1)
				}
			} else if err := os.WriteFile(outputPath, outputData, 0644); err != nil {
				fmt.Fprintf(os.Stderr, "Error writing output file: %v\n", err)
				os.Exit(1)
			}

			paths, operations := countRoutes(spec)
			logf("✅ %d operations across %d paths -> %s\n", operations, paths, outputPath)

			// --strict turns an incomplete spec into a build failure, which is
			// what makes respec usable as a CI gate.
			if strict && warnings > 0 {
				fmt.Fprintf(os.Stderr, "\n%d warning(s) and --strict was set.\n", warnings)
				os.Exit(1)
			}
		},
	}

	// versionCmd prints the version information.
	var versionCmd = &cobra.Command{
		Use:   "version",
		Short: "Print the version number of respec",
		Run: func(cmd *cobra.Command, args []string) {
			fmt.Printf("respec version %s\n", version)
			fmt.Printf("commit: %s\n", commit)
			fmt.Printf("built at: %s\n", date)
		},
	}

	// initCmd creates a default .respec.yaml file.
	var initCmd = &cobra.Command{
		Use:   "init",
		Short: "Create a default .respec.yaml configuration file",
		Long:  "Creates a default .respec.yaml file in the current directory. This file contains examples and documentation for all configuration options.",
		Run: func(cmd *cobra.Command, args []string) {
			configFileName := ".respec.yaml"
			if _, err := os.Stat(configFileName); err == nil {
				fmt.Fprintf(os.Stderr, "Error: '%s' already exists in the current directory. Aborting.\n", configFileName)
				os.Exit(1)
			}

			err := os.WriteFile(configFileName, []byte(defaultRespecYAML), 0644)
			if err != nil {
				fmt.Fprintf(os.Stderr, "Error writing %s: %v\n", configFileName, err)
				os.Exit(1)
			}
			fmt.Printf("✅ Successfully created '%s'.\n", configFileName)
		},
	}

	// validateCmd validates an OpenAPI specification file.
	var validateCmd = &cobra.Command{
		Use:   "validate <file>",
		Short: "Validate an OpenAPI specification file",
		Long:  "Validates that the given OpenAPI specification file (JSON or YAML) conforms to the OpenAPI 3.1 standard.",
		Args:  cobra.ExactArgs(1),
		Run: func(cmd *cobra.Command, args []string) {
			specPath := args[0]
			fmt.Printf("Validating specification at: %s\n", specPath)

			loader := openapi3.NewLoader()
			doc, err := loader.LoadFromFile(specPath)
			if err != nil {
				fmt.Fprintf(os.Stderr, "❌ Error loading specification file: %v\n", err)
				os.Exit(1)
			}

			err = doc.Validate(loader.Context)
			if err != nil {
				fmt.Fprintf(os.Stderr, "❌ Specification is invalid:\n%v\n", err)
				os.Exit(1)
			}

			fmt.Println("✅ Specification is valid.")
		},
	}

	// Register all commands and flags.
	rootCmd.AddCommand(versionCmd)
	rootCmd.AddCommand(initCmd)
	rootCmd.AddCommand(validateCmd)
	rootCmd.Flags().StringVarP(&outputPath, "output", "o", "openapi.yaml", "Output file for the spec; use - for stdout (.json selects JSON)")
	rootCmd.Flags().BoolVarP(&quiet, "quiet", "q", false, "Suppress progress and diagnostics")
	rootCmd.Flags().BoolVarP(&verbose, "verbose", "v", false, "Also show informational diagnostics")
	rootCmd.Flags().BoolVar(&strict, "strict", false, "Exit non-zero if anything could not be resolved")

	// Execute the root command.
	if err := rootCmd.Execute(); err != nil {
		os.Exit(1)
	}
}
